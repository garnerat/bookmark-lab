"""Hand-labeled synthetic search cards.

Nothing here is a scrape of a real store. The notes say why the label was
chosen. `fits` is 1 when the product is the item the query asks for.

`case` is a tag for reading errors later:
  exact       obvious match
  extra_ok    query constraint is met, and the card adds something unasked
  paraphrase  the card uses different words covered by the rules in dataset.py
  near_miss   same family of product, one requirement missed
  off_topic   a different product

Rows are grouped by badge so the file is easy to read. That grouping is not
a rank on a results page.
"""


def Q(query_id, split, query, results):
    return {"id": query_id, "split": split, "query": query, "results": results}


def R(badge, title, details, fits, case, note):
    return {
        "badge": badge,
        "title": title,
        "details": details,
        "fits": fits,
        "case": case,
        "note": note,
    }


